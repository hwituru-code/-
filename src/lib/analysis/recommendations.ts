export function generateRecommendations(insights: InsightsResult, limit = 5): Recommendation[] {
  const recs: Recommendation[] = [];

  for (const bp of insights.bodyPartInsights) {
    const factor = bp.topFactors[0] as FactorCorrelation | undefined;
    if (factor) {
      const pairKey = `${bp.bodyPart}::${factor.tag}`;
      const message = PAIR_ADVICE[pairKey] ?? TAG_ADVICE[factor.tag];
      if (message) {
        recs.push({ bodyPart: bp.bodyPart, tag: factor.tag, lift: factor.lift, message });
        continue;
      }
    }
    const fallback = BODY_PART_FALLBACK[bp.bodyPart];
    if (fallback) {
      recs.push({ bodyPart: bp.bodyPart, tag: "일반", lift: 1, message: fallback });
    }
  }

  return recs
    .sort((a, b) => b.lift - a.lift)
    .slice(0, limit);
}

export function describeBodyPartInsight(bp: BodyPartInsight): string {
  const parts = [`최근 ${bp.occurrenceCount}회 기록됨`];
  if (bp.avgSeverity !== null) {
    parts.push(`평균 통증 강도 ${bp.avgSeverity.toFixed(1)}/10`);
  }
  return parts.join(" · ");
}
